#!/usr/bin/env python3
"""Write the bundle's registry lock: Meridian's own dependency tree, at the
versions the pinned game uses.

The launcher refuses a mod lock that pins a game package at another version
or with other dependencies than the game's own graph. A lock resolved afresh
(`horizon-launcher native-lock --update-lock`) takes the newest versions; a
copy of the whole game lock breaks on any package the game moves. This keeps
only the registry packages reachable from Meridian's crates (not through the
SDK's `horizon-*` crates), each at the game's version and checksum:

1. the game's `Cargo.lock` at the pin (from GitHub, or GAME_LOCK=path);
2. Cargo resolves a staged copy of the bundle from it, offline, keeping its
   versions and dropping what the bundle does not use;
3. the registry closure of the `meridian-*` crates is written as
   `mixins/meridian/Cargo.lock`.

Run it after changing the pin or a registry dependency, then build.
"""
import os
import pathlib
import subprocess
import sys
import tempfile
import tomllib
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
BUNDLE = ROOT / "mixins/meridian"
REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"


def game_lock(pin):
    path = os.environ.get("GAME_LOCK")
    if path:
        return pathlib.Path(path).read_text()
    url = f"https://raw.githubusercontent.com/horizon-rust/horizon/{pin}/Cargo.lock"
    with urllib.request.urlopen(url) as reply:
        return reply.read().decode()


def main():
    pin = tomllib.loads((BUNDLE / "horizon-mod.toml").read_text())["native"]["horizon"]
    sdk = BUNDLE / ".horizon/sdk"
    if not (sdk / "build").exists() or (sdk / "build").read_text().strip() != pin:
        sys.exit("The pinned SDK is not in mixins/meridian/.horizon/sdk; run tools/check-adapter.sh first")
    source = (BUNDLE / "Cargo.toml").read_text()
    source = source.replace('path = ".horizon/sdk/api/crates/horizon-mod-api"',
                            f'path = "{sdk / "api/crates/horizon-mod-api"}"')
    source = source.replace('path = "src/', f'path = "{BUNDLE}/src/')
    with tempfile.TemporaryDirectory(prefix="meridian-lock-") as temporary:
        stage = pathlib.Path(temporary)
        (stage / "Cargo.toml").write_text(source + "\n[workspace]\n")
        (stage / "Cargo.lock").write_text(game_lock(pin))
        subprocess.run(["cargo", "metadata", "--format-version", "1", "--offline",
                        "--manifest-path", str(stage / "Cargo.toml")],
                       check=True, stdout=subprocess.DEVNULL)
        lock = tomllib.loads((stage / "Cargo.lock").read_text())
    packages = lock["package"]
    by_name = {}
    for p in packages:
        by_name.setdefault(p["name"], []).append(p)

    def resolve(dep):
        name, *version = dep.split(" ")
        found = [p for p in by_name[name] if not version or p["version"] == version[0]]
        if len(found) != 1:
            sys.exit(f"ambiguous dependency {dep}")
        return found[0]

    stack = [resolve(d) for p in packages if p["name"].startswith("meridian-")
             for d in p.get("dependencies", [])]
    keep = {}
    while stack:
        p = stack.pop()
        if p.get("source") != REGISTRY or (p["name"], p["version"]) in keep:
            continue
        keep[(p["name"], p["version"])] = p
        stack.extend(resolve(d) for d in p.get("dependencies", []))
    kept = sorted(keep.values(), key=lambda p: (p["name"], p["version"]))
    names = [p["name"] for p in kept]
    out = ["# This file is automatically @generated by Cargo.",
           "# It is not intended for manual editing.", "version = 4", ""]
    for p in kept:
        out += ["[[package]]", f'name = "{p["name"]}"', f'version = "{p["version"]}"',
                f'source = "{p["source"]}"', f'checksum = "{p["checksum"]}"']
        deps = [d if names.count(d.split(" ")[0]) > 1 else d.split(" ")[0]
                for d in p.get("dependencies", [])]
        if deps:
            out += ["dependencies = ["] + [f' "{d}",' for d in deps] + ["]"]
        out.append("")
    (BUNDLE / "Cargo.lock").write_text("\n".join(out))
    print(f"mixins/meridian/Cargo.lock: {len(kept)} registry packages at the game's versions ({pin[:7]})")


if __name__ == "__main__":
    main()
