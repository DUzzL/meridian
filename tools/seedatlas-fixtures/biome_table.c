/* Prints the 26.3 biome table (exists, name, colour) as Rust, from the
 * Seed Atlas engine. Development tool only: not part of the mod. */
#include "biomes.h"
#include "util.h"
#include <stdio.h>

int main(void)
{
    unsigned char colors[256][3];
    initBiomeColors(colors);
    printf("// Generated by tools/seedatlas-fixtures/biome_table.c from the Seed Atlas\n");
    printf("// engine (MC 26.3); do not edit by hand.\n\n");
    printf("/// (exists, name, colour 0xRRGGBB) by biome id.\n");
    printf("pub const BIOMES: [(bool, &str, u32); 256] = [\n");
    for (int id = 0; id < 256; id++) {
        int exists = biomeExists(MC_26_3, id);
        const char *name = biome2str(MC_26_3, id);
        printf("    (%s, \"%s\", 0x%02X%02X%02X),\n", exists ? "true" : "false",
               name ? name : "", colors[id][0], colors[id][1], colors[id][2]);
    }
    printf("];\n");
    return 0;
}
